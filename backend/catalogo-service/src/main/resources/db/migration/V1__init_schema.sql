CREATE TABLE IF NOT EXISTS categorias (
    id VARCHAR(40) PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL DEFAULT '',
    imagen VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS insumos (
    id VARCHAR(40) PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE,
    unidad VARCHAR(5) NOT NULL,
    stock DOUBLE NOT NULL,
    minimo DOUBLE NOT NULL
);

CREATE TABLE IF NOT EXISTS productos (
    codigo VARCHAR(20) PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    categoria_id VARCHAR(40) NOT NULL,
    precio INT NOT NULL,
    precio_anterior INT NULL,
    stock INT NOT NULL,
    stock_critico INT NOT NULL DEFAULT 0,
    imagen VARCHAR(255) NOT NULL DEFAULT '',
    descripcion TEXT NOT NULL,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

CREATE TABLE IF NOT EXISTS receta_items (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    producto_codigo VARCHAR(20) NOT NULL,
    insumo_id VARCHAR(40) NOT NULL,
    cantidad DOUBLE NOT NULL,
    CONSTRAINT fk_receta_producto FOREIGN KEY (producto_codigo) REFERENCES productos (codigo) ON DELETE CASCADE,
    CONSTRAINT fk_receta_insumo FOREIGN KEY (insumo_id) REFERENCES insumos (id),
    CONSTRAINT uq_receta_insumo UNIQUE (producto_codigo, insumo_id)
);

